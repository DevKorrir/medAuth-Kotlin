@Composable
fun Modifier.shimmerBackground(): Modifier {
    val transition = rememberInfiniteTransition(label = "shimmer")
    val translateAnim by transition.animateFloat(
        initialValue = 0f,
        targetValue = 1000f,
        animationSpec = infiniteRepeatable(
            animation = tween(durationMillis = 1000, easing = FastOutLinearInEasing),
            repeatMode = RepeatMode.Restart
        ),
        label = "shimmer_anim"
    )

    val color = Color.LightGray.copy(alpha = 0.4f)
    val colorAccent = Color.LightGray.copy(alpha = 0.8f)

    val brush = Brush.linearGradient(
        colors = listOf(color, colorAccent, color),
        start = Offset.Zero,
        end = Offset(x = translateAnim, y = translateAnim)
    )

    return this.background(brush)
}

@Composable
fun LoadingShimmer(modifier: Modifier = Modifier) {
    Box(
        modifier = modifier
            .background(Color.LightGray.copy(alpha = 0.2f))
            .shimmerBackground()
    )
}
